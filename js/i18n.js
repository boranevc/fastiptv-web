// UI language: Turkish on Turkish TVs, English everywhere else (LG requires English support).
// The TV's display language comes from webOS (webOSSystem.locale) or the browser; ?lang=tr|en forces one for testing.

function detect() {
  let forced = null;
  try { forced = new URLSearchParams(location.search).get('lang') || localStorage.getItem('tvip.lang'); } catch { /* storage unavailable */ }
  const raw = forced || window.webOSSystem?.locale || navigator.languages?.[0] || navigator.language || 'en';
  return { lang: /^tr/i.test(raw) ? 'tr' : 'en', raw };
}

